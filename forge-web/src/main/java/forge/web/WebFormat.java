package forge.web;

import forge.deck.Deck;
import forge.game.GameType;

/**
 * The formats the web server offers. Adding one is adding an entry here, then playing it through
 * the scripted client in the tests to check every dialog it raises has a screen.
 */
public enum WebFormat {
    DANDAN(GameType.DanDan, "DanDan"),
    MOMIR(GameType.MomirBasic, "Momir Basic");

    public final GameType gameType;
    public final String label;

    WebFormat(GameType gameType, String label) {
        this.gameType = gameType;
        this.label = label;
    }

    /** The deck each seat plays; both of these formats build it themselves. */
    public Deck deck() {
        return gameType.autoGenerateDeck(null);
    }

    public static WebFormat parse(String s) {
        for (WebFormat f : values()) {
            if (f.name().equalsIgnoreCase(s)) {
                return f;
            }
        }
        return null;
    }
}
