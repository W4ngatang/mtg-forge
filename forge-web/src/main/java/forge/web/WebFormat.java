package forge.web;

import forge.deck.Deck;
import forge.game.GameType;

/**
 * The formats the web server offers. Adding one is adding an entry here, then playing it through
 * the scripted client in the tests to check every dialog it raises has a screen.
 */
public enum WebFormat {
    DANDAN(GameType.DanDan, "DanDan", "Both players share one library and graveyard. The host picks the shared deck.", true),
    MOMIR(GameType.MomirBasic, "Momir Basic", "Decks of basic lands; discard a card and pay X to make a random creature with mana value X.", false),
    BASIC_LAND_GAME(GameType.BasicLandGame, "Basic Land Game",
            "Ten of each basic. Each basic does something when played; win with all five types, or five of one.", false);

    public final GameType gameType;
    public final String label;
    public final String description;
    /** Whether the host picks a deck; otherwise the format builds its own. */
    public final boolean hostPicksDeck;

    WebFormat(GameType gameType, String label, String description, boolean hostPicksDeck) {
        this.gameType = gameType;
        this.label = label;
        this.description = description;
        this.hostPicksDeck = hostPicksDeck;
    }

    /** The deck each seat plays: the host's pick when there is one, otherwise the format's own. */
    public Deck deck(Deck hostPick) {
        return hostPicksDeck && hostPick != null ? hostPick : gameType.autoGenerateDeck(null);
    }

    public static WebFormat parse(String s) {
        for (WebFormat f : values()) {
            if (f.name().equalsIgnoreCase(s)) {
                return f;
            }
        }
        return null;
    }
}
